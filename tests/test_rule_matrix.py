# rules that fire on ordinary packaging by design (they ask for review, they do not mean "attack")
ROUTINE = {"unknown-command", "build-time-download", "dependency-fetch", "registry-install", "vcs-fetch",
           "path-modification", "base64-decode"}
MUST_FIRE = [(line, rule) for line, rule in CASES if rule != "!"]
MUST_BE_QUIET = [line for line, rule in CASES if rule == "!"]


def findings(line):
    return scan({"PKGBUILD": f"build() {{\n  {line}\n}}"})


@pytest.mark.parametrize("line,rule", MUST_FIRE)
def test_fires(line, rule):
    assert rule in {f.rule for f in findings(line)}


@pytest.mark.parametrize("line", MUST_BE_QUIET)
def test_quiet(line):
    loud = [(f.rule, f.severity) for f in findings(line) if f.severity in ("danger", "caution") and f.rule not in ROUTINE]
    assert not loud
